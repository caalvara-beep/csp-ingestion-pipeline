// SECTION 5: HELPER UTILITIES
// =================================================================
function writeLogsToMapper(mapperSpreadsheet, logEntries) {
  let logSheet = mapperSpreadsheet.getSheetByName("Logs");
  if (!logSheet) {
    logSheet = mapperSpreadsheet.insertSheet("Logs");
    logSheet.appendRow(["Timestamp", "Run Number", "Status", "Details"]);
    logSheet.getRange("A1:D1").setFontWeight("bold").setBackground("#F4F6F8");
  }

  if (logEntries.length > 0) {
    const lastRow = logSheet.getLastRow() + 1;
    logSheet.getRange(lastRow, 1, logEntries.length, 4).setValues(logEntries);
  }
}

function parseColumnIndex(col) {
  if (typeof col === 'number') return col;
  if (!col) return 1;
  col = col.toString().toUpperCase().trim();
  
  // Handle numeric string conversion
  if (!isNaN(col)) return parseInt(col, 10);

  // Convert A, B, C ... Z, AA, AB to 1-based index
  let base = 0;
  for (let i = 0; i < col.length; i++) {
    base = base * 26 + col.charCodeAt(i) - 64;
  }
  return base > 0 ? base : 1;
}

function normalizeMatrixValue(value) {
  if (value === undefined || value === null) return "";
  if (value instanceof Date) {
    return Utilities.formatDate(value, Session.getScriptTimeZone(), "yyyy-MM-dd'T'HH:mm:ss'Z'");
  }
  return String(value);
}

function normalizeMatrixResult(matrixResult) {
  const safeResult = {};
  Object.keys(matrixResult).forEach(tabName => {
    const tab = matrixResult[tabName] || { headers: [], rows: [] };
    safeResult[tabName] = {
      headers: (tab.headers || []).map(header => normalizeMatrixValue(header)),
      rows: (tab.rows || []).map(row => (row || []).map(cell => ({
        value: normalizeMatrixValue(cell && cell.value),
        destCol: cell && cell.destCol !== undefined ? cell.destCol : 0
      })))
    };
  });
  return safeResult;
}