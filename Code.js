function importMatrixToDestination(payload) {
  const { matrixData, runNumber } = payload;
  const destUrl = SYSTEM_SETTINGS.destinationUrl;
  const mapperUrl = SYSTEM_SETTINGS.mapperUrl;

  if (!destUrl || !mapperUrl || !matrixData) {
    throw new Error("v" + APP_VERSION + " Error: System destination URL, mapper URL, and matrix data are required.");
  }

  const destSpreadsheet = SpreadsheetApp.openByUrl(destUrl);
  const mapperSpreadsheet = SpreadsheetApp.openByUrl(mapperUrl);

  const executionLog = [];
  const timestamp = new Date().toISOString();

  try {
    for (const tabCategory in matrixData) {
      const tabObj = matrixData[tabCategory];
      if (!tabObj || !tabObj.rows || tabObj.rows.length === 0) continue;

      let destSheet = destSpreadsheet.getSheetByName(tabCategory);
      if (!destSheet) {
        destSheet = destSpreadsheet.insertSheet(tabCategory);
      }

      const rowsToWrite = tabObj.rows.map(row => row.map(cell => cell.value));
      const startRow = destSheet.getLastRow() === 0 ? 1 : destSheet.getLastRow() + 1;

      destSheet.getRange(startRow, 1, rowsToWrite.length, rowsToWrite[0].length).setValues(rowsToWrite);

      executionLog.push([
        timestamp,
        runNumber,
        "SUCCESS",
        `Appended ${rowsToWrite.length} rows to destination tab '${tabCategory}'.`
      ]);
    }
  } catch (err) {
    executionLog.push([
      timestamp,
      runNumber,
      "ERROR",
      `Execution failed: ${err.message}`
    ]);
    writeLogsToMapper(mapperSpreadsheet, executionLog);
    throw err;
  }

  writeLogsToMapper(mapperSpreadsheet, executionLog);
  return { success: true, message: `Run #${runNumber}: Data successfully imported into Destination Sheet!` };
}

